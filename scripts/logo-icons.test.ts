import { existsSync, readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';
import { expect, it } from 'vitest';
import { LOGO_MARK_PATH } from '../src/styles/logoMark.ts';
import { INK } from '../src/styles/palette.ts';
import { PNG_FILES, SVG_FILES, renderPng } from './logo-icons.ts';

const file = (name: string) => fileURLToPath(new URL(`../${name}`, import.meta.url));

it('draws the mark as nine closed squares', () => {
  const squares = LOGO_MARK_PATH.split('M').slice(1);
  expect(squares).toHaveLength(9);
  for (const square of squares) {
    expect(square.trim().endsWith('Z')).toBe(true);
    expect(square.replace('Z', '').trim().split(/\s+/)).toHaveLength(8);
  }
});

it('keeps the committed SVGs in step with the mark (npm run icons)', () => {
  for (const [name, svg] of Object.entries(SVG_FILES)) expect(readFileSync(file(name), 'utf8'), name).toBe(svg);
});

it('commits each PNG icon at its size, drawn from the current mark (npm run icons)', async () => {
  for (const [name, spec] of Object.entries(PNG_FILES)) {
    const png = readFileSync(file(name));
    expect(png.subarray(1, 4).toString('latin1'), name).toBe('PNG');
    // The IHDR chunk's width and height.
    expect([png.readUInt32BE(16), png.readUInt32BE(20)], name).toEqual([spec.size, spec.size]);
    // Compare pixels, not bytes, so a different PNG encoder can't fail it; a moved square can.
    const pixels = (image: Buffer) => sharp(image).ensureAlpha().raw().toBuffer();
    const [committed, fresh] = await Promise.all([pixels(png), renderPng(spec).then(pixels)]);
    expect(committed.length, name).toBe(fresh.length);
    let worst = 0;
    for (let i = 0; i < fresh.length; i++) worst = Math.max(worst, Math.abs(committed[i] - fresh[i]));
    expect(worst, name).toBeLessThanOrEqual(8);
  }
});

it('links every icon from index.html at a root path, so Vite puts it under either base', () => {
  const html = readFileSync(file('index.html'), 'utf8');
  const links = [...html.matchAll(/<link rel="(?:icon|apple-touch-icon)"[^>]*href="([^"]+)"/g)].map((match) => match[1]);
  expect(links.sort()).toEqual(['/apple-touch-icon.png', '/favicon-32.png', '/favicon.svg']);
  for (const href of links) expect(existsSync(file(`public${href}`)), href).toBe(true);
});

it('links the web app manifest at a root path, so Vite puts it under either base', () => {
  const html = readFileSync(file('index.html'), 'utf8');
  expect(html).toMatch(/<link rel="manifest" href="\/manifest\.webmanifest" \/>/);
  expect(existsSync(file('public/manifest.webmanifest'))).toBe(true);
});

it('keeps the manifest inside the site base and in step with the icon files', () => {
  const html = readFileSync(file('index.html'), 'utf8');
  const manifest = JSON.parse(readFileSync(file('public/manifest.webmanifest'), 'utf8'));
  // Vite copies public/ byte for byte, so the manifest's URLs resolve against its own address: a
  // "/icon.png" would leave /BrainrotTCG/ (GitHub Pages) and 404.
  const manifestUrl = new URL('https://x.test/BrainrotTCG/manifest.webmanifest');
  const inSite = (value: string) => {
    const url = new URL(value, manifestUrl);
    expect(url.origin, value).toBe(manifestUrl.origin);
    expect(url.pathname.startsWith('/BrainrotTCG/'), `${value} -> ${url.pathname}`).toBe(true);
    return url.pathname.slice('/BrainrotTCG/'.length);
  };
  const start = inSite(manifest.start_url);
  const scope = inSite(manifest.scope);
  expect(start.startsWith(scope)).toBe(true);

  // minimal-ui, not standalone: an iOS home-screen app in standalone mode has storage of its own,
  // apart from Safari's, so a player's save and identity would not follow them into it.
  expect(manifest.display).toBe('minimal-ui');
  expect(manifest.name).toBe('Brainrot TCG');
  expect(manifest.short_name).toBe('Brainrot TCG');
  const themeMeta = /<meta name="theme-color" content="([^"]+)"/.exec(html)![1];
  expect(manifest.theme_color).toBe(INK);
  expect(manifest.background_color).toBe(INK);
  expect(themeMeta).toBe(INK);

  const pngs: string[] = [];
  for (const icon of manifest.icons) {
    const target = inSite(icon.src);
    expect(existsSync(file(`public/${target}`)), icon.src).toBe(true);
    if (icon.type === 'image/svg+xml') {
      expect(icon.sizes, icon.src).toBe('any');
      expect(`public/${target}` in SVG_FILES, icon.src).toBe(true);
      continue;
    }
    expect(icon.type, icon.src).toBe('image/png');
    expect(`public/${target}` in PNG_FILES, `${icon.src} is generated by scripts/logo-icons.ts`).toBe(true);
    const png = readFileSync(file(`public/${target}`));
    expect(icon.sizes, icon.src).toBe(`${png.readUInt32BE(16)}x${png.readUInt32BE(20)}`);
    pngs.push(`public/${target}`);
    if (icon.purpose === 'maskable') expect(target, icon.src).toMatch(/^icon-maskable-/);
  }
  // Every PNG icon the script writes is listed, once.
  expect(pngs.sort()).toEqual(Object.keys(PNG_FILES).sort());
  expect(manifest.icons.filter((icon: { purpose?: string }) => icon.purpose === 'maskable')).toHaveLength(2);
  expect(manifest.icons.filter((icon: { purpose?: string }) => icon.purpose === 'any')).toHaveLength(2);
});

it('includes valid JSON-LD structured data and crawlable semantic copy in index.html', () => {
  const html = readFileSync(file('index.html'), 'utf8');

  const jsonLdMatch = html.match(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/);
  expect(jsonLdMatch).toBeTruthy();
  const jsonLd = JSON.parse(jsonLdMatch![1]);
  expect(jsonLd['@context']).toBe('https://schema.org');
  expect(jsonLd['@type']).toEqual(['WebApplication', 'VideoGame']);
  expect(jsonLd.name).toBe('Brainrot TCG');
  expect(jsonLd.url).toBe('https://brainrottcg.pages.dev/');

  expect(html).toContain('<noscript>');
  expect(html).toContain('Brainrot TCG');
  expect(jsonLd.alternateName).toEqual(['Brainrot Trading Card Game']);
  expect(html).toContain('<p><strong>Brainrot TCG (Brainrot Trading Card Game)</strong></p>');
  expect(html).not.toMatch(/Brain Rot/);
});
